const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const root = path.resolve(__dirname, '..');
const docsPath = path.join(root, 'DOCS.md');
const packagePath = path.join(root, 'package.json');
const startMarker = '<!-- GENERATED:START -->';
const endMarker = '<!-- GENERATED:END -->';

function readDirectories(relativePath) {
  // Ignore local scratch/build directories so a clean CI checkout produces
  // the same inventory as a developer workspace. Include new source files.
  const files = execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', '-z', relativePath], {
    cwd: root,
    encoding: 'utf8',
  }).split('\0');
  const directories = files.map((file) => file.slice(relativePath.length + 1).split('/'))
    .filter((parts) => parts.length > 1 && !parts[0].startsWith('.'))
    .map((parts) => parts[0]);
  return [...new Set(directories)].sort();
}

function buildGeneratedSection() {
  const packageJson = JSON.parse(fs.readFileSync(packagePath, 'utf8'));
  const sourceDirectories = readDirectories('src');
  const documentationDirectories = readDirectories('docs');
  const verificationScripts = Object.keys(packageJson.scripts)
    .filter((name) => name === 'test' || name === 'typecheck' || name === 'build' || name.startsWith('qa:') || name.startsWith('ui:') || name.startsWith('perf:'))
    .sort();

  return [
    startMarker,
    '## Generated Project Inventory',
    '',
    'This section is generated by `npm run docs:generate`. Do not edit it manually; use `npm run docs:check` to verify it is current.',
    '',
    '### Source Roots',
    '',
    ...sourceDirectories.map((directory) => `- \`src/${directory}/\``),
    '',
    '### Documentation Roots',
    '',
    ...documentationDirectories.map((directory) => `- \`docs/${directory}/\``),
    '',
    '### Verification Commands',
    '',
    ...verificationScripts.map((script) => `- \`npm run ${script}\``),
    '',
    endMarker
  ].join('\n');
}

function updateDocumentation(content, generatedSection) {
  const startIndex = content.indexOf(startMarker);
  const endIndex = content.indexOf(endMarker);

  if (startIndex === -1 && endIndex === -1) {
    return `${content.trimEnd()}\n\n${generatedSection}\n`;
  }

  if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) {
    throw new Error('DOCS.md has incomplete generated-section markers. Restore both markers before generating documentation.');
  }

  return `${content.slice(0, startIndex)}${generatedSection}${content.slice(endIndex + endMarker.length)}`;
}

const checkOnly = process.argv.includes('--check');
const currentDocumentation = fs.readFileSync(docsPath, 'utf8');
const nextDocumentation = updateDocumentation(currentDocumentation, buildGeneratedSection());

if (checkOnly) {
  if (currentDocumentation !== nextDocumentation) {
    console.error('DOCS.md is out of date. Run: npm run docs:generate');
    process.exitCode = 1;
  } else {
    console.log('DOCS.md generated inventory is current.');
  }
} else {
  fs.writeFileSync(docsPath, nextDocumentation);
  console.log('DOCS.md generated inventory updated.');
}
